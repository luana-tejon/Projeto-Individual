// LÓGICA DE VIRAR E COMPARAR CARTAS
// guarda a primeira e a segunda carta que o jogador vira
let primeira = null;
let segunda = null;

// controla se o jogador pode clicar
let podeClicar = true;

function viradaCarta(carta) {

    // evita virar enquanto está verificando par
    if (!podeClicar) {
        return;
    }

    // evita clicar 2x na mesma carta
    if (carta.classList.contains("virada")) { // verifica se o elemento possui uma classe(virada)
        console.log("Virada realizada");
        return;
    }

    // contains muito usado em apis antigas mas hoje em dia é subistuindo por includes()
    // O código não funciona com .includes() porque classList não é um array(é uma matriz), e sim um objeto do tipo DOMTokenList(class).
    // O método .includes() é de arrays e strings, não de DOMTokenList.

    // vira a carta visualmente
    carta.classList.add("virada"); // add a class
    // se ainda não tem a primeira carta
    if (primeira === null) {
        primeira = carta;
    } else {
        // se já tem a primeira, essa é a segunda
        segunda = carta;
        // agora verifica se formam par
        verificarPar();
    }
}

let cont = 0;

let jogadas = 0;

function verificarPar() {

    // bloqueia cliques enquanto verifica
    podeClicar = false;

    // pega os nomes das cartas (pelo dataset)
    let nome1 = primeira.dataset.name; // verefica pelo nome do json
    let nome2 = segunda.dataset.name; //

    jogadas++;
    console.log(`${jogadas}`);
    
    // se forem iguais → PAR
    if (nome1 == nome2) { //ele vai adicionar se passar

        primeira.classList.add("bloqueada"); // add class
        segunda.classList.add("bloqueada"); // add class

        // conta o par
        cont++;

        // aguarda a animação da carta virar antes de finalizar o jogo
        setTimeout(() => {
            finalizadorJogo(); 
             // libera o jogo para continuar
          resetarSelecao();
        }, 1000);  

        // altera as reacoes da nostalgia 
        nostagiaImg(nome1,nome2);

    } else {
        // NÃO é par
        setTimeout(() => {
            primeira.classList.remove("virada"); // revome a class
            segunda.classList.remove("virada");

            resetarSelecao();
        }, 800);

        // se quiser pontuação, chama aqui
        atualizarPontos();
        // altera as reacoes da nostalgia 
        nostagiaImg(nome1,nome2)
    }
}

function finalizadorJogo() {
    if (cont === 6) {
        determinarRank(pontos);
        salvarResultado();
    }
}

function resetarSelecao() {
    // limpa as cartas selecionadas
    primeira = null;
    segunda = null;
    podeClicar = true;// libera cliques de novo
}

