// FUNÇÃO EMBARALHAR LISTAS (Fisher-Yates)
// Essa função pega uma lista e mistura seus valores.
// É o algoritmo mais usado para embaralhar sem repetição.
// Percorre de trás para frente trocando os itens de lugar.
function embaralhar(lista) {
    for (let i = lista.length - 1; i > 0; i--) {

        // sorteia um índice entre 0 e i
        const j = Math.floor(Math.random() * (i + 1));

        // troca os valores de lista[i] com lista[j]
        [lista[i], lista[j]] = [lista[j], lista[i]];
    }
    return lista;
}

