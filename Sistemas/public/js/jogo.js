// salvar Resultado 
function salvarResultado(){
    var segundoVar = TempoConclusao;
    var pontosVar = pontos;
    var jogadasVar = jogadas;
    var ranksVar = rank;
    var fkUsuarioVar = sessionStorage.FK_USUARIO;
    
    
    sessionStorage.SEGUNDOS_JOGO = segundoVar;
    sessionStorage.PONTOS_JOGO = pontosVar;
    sessionStorage.JOGADAS_JOGO = jogadasVar;
    sessionStorage.RANKS_JOGO = ranksVar;

    // Enviando o valor da nova input
    fetch("/partidas/cadastrar", { // arquivo, função do arquivo
      method: "POST",
      headers: {
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        // crie um atributo que recebe o valor recuperado aqui
        // Agora vá para o arquivo routes/usuario.js
        segundosServer: segundoVar,
        pontosServer: pontosVar,
        jogadasServer: jogadasVar,
        ranksServer: ranksVar,
        fkUsuarioServer: fkUsuarioVar,
    }),
})
      .then(function (resposta) {
        console.log("resposta: ", resposta);

        if (resposta.ok) {

          setTimeout(() => {
            alert(`Jogo finalizado...`)
            window.location = "dashboard.html";
          }, 500);

          limparFormulario();
          finalizarAguardar();
        } else {
          throw "Houve um erro ao tentar realizar a inserção do jogo!";
        }
    })
      .catch(function (resposta) {
          console.log(`#ERRO: ${resposta}`);
        // finalizarAguardar();
      });

      return false;
}


